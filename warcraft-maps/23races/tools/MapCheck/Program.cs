using War3Net.Build;
using War3Net.Build.Script;
using System.Text.RegularExpressions;
using System.Text.Json;
var map=Map.Open(args[0]);
if((int)map.Info!.FormatVersion!=25||(int)map.Info.EditorVersion!=6052)throw new Exception("Not a classic map info file");
if(map.Info.Players.Count!=12||!map.Info.Players.Select(p=>p.Id).Order().SequenceEqual(Enumerable.Range(0,12)))throw new Exception("Missing player slots");
if(map.Environment!.Width!=480||map.Environment.Height!=480||map.Info.PlayableMapAreaWidth!=436||map.Info.PlayableMapAreaHeight!=464)throw new Exception("Terrain/info dimensions differ");
if(map.Units!.Units.Count!=833||map.Regions!.Regions.Count!=64||map.Sounds!.Sounds.Count!=9)throw new Exception("Lost placements");
if(map.Triggers!.Variables.Count!=479||map.CustomTextTriggers!.CustomTextTriggers.Count!=2)throw new Exception("Missing editable triggers");
if(map.ImportedFiles!.Files.Count!=569)throw new Exception("Missing imports");
var outdir=args[1];Directory.CreateDirectory(outdir);
var builder=new MapScriptBuilder();builder.SetDefaultOptionsForMap(map);builder.FindVariableReferences(map);
var script=builder.Build(map).Replace("\r\n","\n");
var end=script.IndexOf("endglobals")+"endglobals".Length;
script=script.Insert(end,"\n"+map.CustomTextTriggers.GlobalCustomScriptCode.Code+"\n");
var custom=map.Triggers.TriggerItems.OfType<TriggerDefinition>().Where(t=>t.IsCustomTextTrigger).ToArray();
if(custom.Length!=1||custom[0].Name!="Recovery23Races")throw new Exception("Unexpected recovery entry");
var bootstrap=map.CustomTextTriggers.CustomTextTriggers[0].Code;
var pattern=@"function InitTrig_Recovery23Races takes nothing returns nothing.*?endfunction";
if(!Regex.IsMatch(script,pattern,RegexOptions.Singleline))throw new Exception("No recovery trigger in generated script");
script=Regex.Replace(script,pattern,_=>bootstrap.Trim(),RegexOptions.Singleline);
File.WriteAllText(Path.Combine(outdir,"editor-generated.j"),script);
File.WriteAllText(Path.Combine(outdir,"original-gameplay.j"),map.Script!.Replace("\r\n","\n").Replace("\r","\n"));
var summary=new{infoVersion=25,editorVersion=6052,terrainWidth=480,terrainHeight=480,players=12,placedUnits=821,startLocations=12,regions=64,sounds=9,variables=479,imports=569,codeHeaderBytes=System.Text.Encoding.UTF8.GetByteCount(map.CustomTextTriggers.GlobalCustomScriptCode.Code),actualWorldEditorRun=false};
File.WriteAllText(Path.Combine(outdir,"metadata-check.json"),JsonSerializer.Serialize(summary,new JsonSerializerOptions{WriteIndented=true}));
Console.WriteLine("PASS War3Net 6.1.2: full downloaded map metadata parses; classic editor formats, 12 players, 833 unit/start records, 64 regions, 9 sounds, 569 imports; reconstructed editor script emitted for pjass");
